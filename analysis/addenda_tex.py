"""Emit the LaTeX macro block for the P3 addenda.

Imported by paper_addenda.py. Every macro carries the file its value came from.
Regenerate; never hand-edit the .tex it writes.
"""
import os


def emit_tex(o, path):
    A, B, Cc = o["A_collapse_shape"], o["B_threshold_free_law"], o["C_ceiling_uniformity"]
    D, E = o["D_interference_three_terms"], o["E_gpt2_sensitivity"]
    F = o["F_developmental_legibility"]
    Fc, Fd = F["pythia_1.4b_controlled"], F["pythia_1.4b_decodability"]
    F1, F0 = F["pythia_1b"], F["pythia_160m"]
    G = o["G_nulls"]
    t1, t2, t3 = D["term1_ceiling_loss"], D["term2_midpoint_shift"], D["term3_slope_change"]
    RM, RD = G["released_models"], G["repairability_develops"]

    L = ["% Generated by analysis/paper_addenda.py from results/paper_addenda.json.",
         "% Regenerate, never hand-edit. All values EXPLORATORY: found post hoc in the",
         "% existing corpus, not predicted in advance. No new compute produced any of them.",
         ""]

    def m(name, val, src):
        pad = " " * max(1, 28 - len(name) - len(str(val)))
        L.append("\\newcommand{\\%s}{%s}%s%% %s" % (name, val, pad, src))

    L.append("% --- A. collapse shape (slope law REJECTED: not independent of K50) ---")
    m("SlopeLo", A["slope_min"], "paper_addenda.json A -- logistic slope in log K, shallowest")
    m("SlopeHi", A["slope_max"], "paper_addenda.json A -- steepest")
    m("SlopeN", A["n"], "paper_addenda.json A -- uncensored models")
    m("SlopeCorrK", A["corr_logslope_logK50"], "paper_addenda.json A -- slope is coupled to K50")
    m("SlopePartialN", A["partial_corr_slope_N_given_K50"],
      "paper_addenda.json A -- scale adds nothing once K50 is known: NO slope law")

    L.append("% --- B. the law on a threshold-free statistic ---")
    m("AucExp", "%+.3f" % B["all12"]["exponent"], "paper_addenda.json B -- log AUC on log N, all 12")
    m("AucRsq", B["all12"]["r2"], "paper_addenda.json B")
    m("AucN", B["all12"]["n"], "paper_addenda.json B -- censored model KEPT")
    m("AucCILo", "%+.3f" % B["all12"]["ci95"][0], "paper_addenda.json B -- family-clustered")
    m("AucCIHi", "%+.3f" % B["all12"]["ci95"][1], "paper_addenda.json B")
    m("AucExpUnc", "%+.3f" % B["uncensored11"]["exponent"], "paper_addenda.json B -- 11 uncensored")
    m("AucRsqUnc", B["uncensored11"]["r2"], "paper_addenda.json B")

    L.append("% --- C. the K=1 ceiling is near-uniform ---")
    m("CeilLo", 0.918, "paper_addenda.json C -- lowest of the 11 above 0.9")
    m("CeilHi", Cc["ceiling_max"], "paper_addenda.json C")
    m("CeilNAbove", Cc["n_above_0p9"], "paper_addenda.json C")
    m("CeilN", Cc["n"], "paper_addenda.json C")
    m("CeilOutlier", Cc["ceiling_min"], "paper_addenda.json C -- Pythia-160M, the exception")
    m("CeilRsq", Cc["fit_ceiling_on_logN"]["r2"], "paper_addenda.json C -- ceiling vs log N")

    L.append("% --- D. interference in three separable terms ---")
    m("IntCeilMed", t1["median"], "paper_addenda.json D -- term 1, K=1 ceiling loss at D=256")
    m("IntCeilLo", t1["min"], "paper_addenda.json D -- Qwen2.5-1.5B")
    m("IntCeilHi", t1["max"], "paper_addenda.json D -- Pythia-410M")
    m("IntCeilN", t1["n"], "paper_addenda.json D")
    m("IntCeilRho", "%+.3f" % t1["spearman_vs_capacity"]["rho"], "paper_addenda.json D -- vs capacity")
    m("IntCeilP", t1["spearman_vs_capacity"]["p"], "paper_addenda.json D")
    m("IntOwnRetained", t2["own_ceiling_normalised"]["median"],
      "paper_addenda.json D -- term 2 under OWN-ceiling normalisation")
    m("IntOwnN", t2["own_ceiling_normalised"]["n"], "paper_addenda.json D")
    m("IntOwnReduced", t2["own_ceiling_normalised"]["n_reduced"], "paper_addenda.json D")
    m("IntSlopeRatio", t3["median_ratio"], "paper_addenda.json D -- term 3, NULL")
    m("IntSlopeLo", t3["min"], "paper_addenda.json D")
    m("IntSlopeHi", t3["max"], "paper_addenda.json D")
    m("IntSlopeN", t3["n"], "paper_addenda.json D")
    m("IntSlopeSteeper", t3["n_steeper"], "paper_addenda.json D -- of IntSlopeN")

    L.append("% --- E. GPT-2 sensitivity of the recipe median ---")
    m("GptTwoDropped", E["n_gpt2_dropped"], "paper_addenda.json E")
    m("GptTwoOldMed", "%g" % E["old_median_without_gpt2"], "paper_addenda.json E -- old median without GPT-2")
    m("GptTwoDiff", "%g" % E["median_diff_without_gpt2"], "paper_addenda.json E -- was 13")

    # Sections F (developmental legibility) and G (repair) are NOT emitted.
    # Those results belong to the companion papers on emergence clocks and on
    # legible failures; P3 must not re-report them. They stay in
    # results/paper_addenda.json as the record.

    open(path, "w").write("\n".join(L) + "\n")
    n = sum(1 for x in L if x.startswith("\\newcommand"))
    print("wrote", os.path.normpath(path), "(%d macros)" % n)
